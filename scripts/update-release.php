<?php

declare(strict_types=1);

// Writes src/Release.php for one Dynoxide release: the version, and for each
// target the SHA-256 of its archive and of the binary inside it.
//
// Usage:
//   php scripts/update-release.php <tag> [--from <dir>] [--out <file>]
//
// Without --from it downloads the release's sha256sums.txt and archives from
// GitHub. With --from it reads them from a directory, such as one filled by
// `gh release download <tag>`. Either way each archive is checked against
// sha256sums.txt and unpacked with the package's own readers, so a change to
// how the engine packages its releases fails here, before a tag.

namespace Dynoxide\Scripts\UpdateRelease;

use Dynoxide\Archive\TarReader;
use Dynoxide\Archive\ZipReader;
use Dynoxide\Platform;

const BASE_URL = 'https://github.com/nubo-db/dynoxide/releases/download';

final class GeneratorException extends \RuntimeException
{
}

/**
 * @return array{version: string, tag: string, targets: array<string, array{archive: string, binary: string}>}
 */
function collect(string $tag, \Closure $fetch, string $workDir): array
{
    if (preg_match('/^v(\d+\.\d+\.\d+(?:-rc\.\d+)?)$/', $tag, $m) !== 1) {
        throw new GeneratorException("Not a Dynoxide release tag: {$tag}");
    }

    $listed = parseSums($fetch('sha256sums.txt'));

    $targets = [];
    foreach (Platform::TARGETS as $target) {
        $platform = Platform::fromTarget($target);
        $name = $platform->archiveName();
        $archive = $fetch($name, $workDir . DIRECTORY_SEPARATOR . $name);

        $archiveHash = hash_file('sha256', $archive);
        if ($archiveHash !== $listed[$name]) {
            throw new GeneratorException("{$name} hashes to {$archiveHash}, but sha256sums.txt says {$listed[$name]}");
        }

        $binary = $workDir . DIRECTORY_SEPARATOR . $target . '-' . $platform->binaryName();
        $platform->isWindows()
            ? ZipReader::extract($archive, $platform->binaryName(), $binary)
            : TarReader::extract($archive, $platform->binaryName(), $binary);

        $targets[$target] = ['archive' => $archiveHash, 'binary' => (string) hash_file('sha256', $binary)];
    }

    return ['version' => $m[1], 'tag' => $tag, 'targets' => $targets];
}

/**
 * Parses sha256sums.txt, which must list exactly the five release archives.
 *
 * @return array<string, string> archive name to hash
 */
function parseSums(string $text): array
{
    $expected = array_map(static fn (string $t): string => Platform::fromTarget($t)->archiveName(), Platform::TARGETS);

    $listed = [];
    foreach (preg_split('/\r?\n/', trim($text)) ?: [] as $line) {
        if (preg_match('/^([0-9a-f]{64}) [ *]?(\S+)$/', $line, $m) !== 1) {
            throw new GeneratorException("sha256sums.txt has a line this script can't read: {$line}");
        }
        if (isset($listed[$m[2]])) {
            throw new GeneratorException("sha256sums.txt lists {$m[2]} twice");
        }
        $listed[$m[2]] = $m[1];
    }

    $missing = array_diff($expected, array_keys($listed));
    $extra = array_diff(array_keys($listed), $expected);
    if ($missing !== [] || $extra !== []) {
        throw new GeneratorException(
            'sha256sums.txt should list exactly the five release archives.'
            . ($missing === [] ? '' : ' Missing: ' . implode(', ', $missing) . '.')
            . ($extra === [] ? '' : ' Not expected: ' . implode(', ', $extra) . '.'),
        );
    }

    return $listed;
}

/**
 * @param array{version: string, tag: string, targets: array<string, array{archive: string, binary: string}>} $release
 */
function render(array $release): string
{
    $rows = '';
    foreach ($release['targets'] as $target => $hashes) {
        $rows .= sprintf(
            "        '%s' => [\n            'archive' => '%s',\n            'binary' => '%s',\n        ],\n",
            $target,
            $hashes['archive'],
            $hashes['binary'],
        );
    }

    return <<<PHP
        <?php

        declare(strict_types=1);

        namespace Dynoxide;

        use Dynoxide\\Exception\\DynoxideException;

        /**
         * The Dynoxide release this version of the package runs.
         *
         * Generated by scripts/update-release.php from {$release['tag']}. Don't edit by hand.
         */
        final class Release
        {
            public const VERSION = '{$release['version']}';
            public const TAG = '{$release['tag']}';

            /** SHA-256 of each target's archive, and of the binary inside it. */
            public const SHA256 = [
        {$rows}    ];

            public static function archiveSha256(string \$target): string
            {
                return self::hashes(\$target)['archive'];
            }

            public static function binarySha256(string \$target): string
            {
                return self::hashes(\$target)['binary'];
            }

            /** @return array{archive: string, binary: string} */
            private static function hashes(string \$target): array
            {
                return self::SHA256[\$target]
                    ?? throw new DynoxideException("Dynoxide {\$target} isn't part of release " . self::TAG);
            }
        }

        PHP;
}

function main(array $argv): int
{
    $args = array_slice($argv, 1);
    $tag = null;
    $from = null;
    $out = dirname(__DIR__) . '/src/Release.php';
    while ($args !== []) {
        $arg = array_shift($args);
        match ($arg) {
            '--from' => $from = array_shift($args),
            '--out' => $out = array_shift($args),
            default => $tag = $arg,
        };
    }
    if ($tag === null || $out === null) {
        fwrite(STDERR, "usage: update-release.php <tag> [--from <dir>] [--out <file>]\n");

        return 2;
    }

    $work = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'dynoxide-release-' . bin2hex(random_bytes(6));
    mkdir($work, 0700);

    $fetch = static function (string $name, ?string $saveAs = null) use ($tag, $from): string {
        if ($from !== null) {
            $path = $from . DIRECTORY_SEPARATOR . $name;
            if (!is_file($path)) {
                throw new GeneratorException("{$path} doesn't exist");
            }

            return $saveAs === null ? (string) file_get_contents($path) : $path;
        }
        $url = BASE_URL . "/{$tag}/{$name}";
        $data = @file_get_contents($url);
        if ($data === false) {
            throw new GeneratorException("Couldn't download {$url}");
        }
        if ($saveAs === null) {
            return $data;
        }
        file_put_contents($saveAs, $data);

        return $saveAs;
    };

    try {
        file_put_contents($out, render(collect($tag, $fetch, $work)));
        fwrite(STDOUT, "Wrote {$out} for {$tag}\n");

        return 0;
    } catch (\Throwable $e) {
        fwrite(STDERR, $e->getMessage() . "\n");

        return 1;
    } finally {
        foreach (glob($work . DIRECTORY_SEPARATOR . '*') ?: [] as $file) {
            unlink($file);
        }
        rmdir($work);
    }
}

if (PHP_SAPI === 'cli' && isset($argv[0]) && realpath($argv[0]) === __FILE__) {
    require dirname(__DIR__) . '/vendor/autoload.php';
    exit(main($argv));
}
